// Generates src/sql.generated.ts from ../../sql/postgres/heapdb.sql, so the
// published package ships the Postgres engine SQL as an exported string.
// Run by `npm run gen` (and before build / typecheck / test); `--check`
// fails if the committed file is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const sqlPath = join(here, "..", "..", "..", "sql", "postgres", "heapdb.sql");
const outPath = join(here, "..", "src", "sql.generated.ts");
const sql = readFileSync(sqlPath, "utf8");
const version =
  /INSERT INTO heapdb\.schema_version \(singleton, version\) VALUES \(true, '([^']+)'\)/.exec(
    sql,
  )?.[1];
if (!version) throw new Error("heapdb.sql: schema_version not found");
const out = `// GENERATED by scripts/gen-sql.mjs from sql/postgres/heapdb.sql. Do not edit.

/** The HeapDB Postgres engine (schema \`heapdb\`): idempotent install / upgrade. */
export const HEAPDB_SQL: string = ${JSON.stringify(sql)};

/** The version \`HEAPDB_SQL\` writes to \`heapdb.schema_version\`. */
export const HEAPDB_SQL_VERSION = ${JSON.stringify(version)};
`;
if (process.argv.includes("--check")) {
  const have = readFileSync(outPath, "utf8");
  if (have !== out) {
    console.error("src/sql.generated.ts is stale: run `npm run gen`");
    process.exit(1);
  }
} else {
  writeFileSync(outPath, out);
}
